package com.ragkb.parse;

/**
 * 解析器识别出的结构块类型。
 *
 * 为什么先把类型标出来再切片:固定长度切分对"标题"和"正文"一视同仁,
 * 于是章节标题经常被留在上一个切片的尾巴上,检索到的片段就失去了"这段在讲什么"的线索。
 * 标出类型后,切片器可以把标题向下"粘"给它所属的正文。
 */
public enum BlockKind {

    /** 章节标题。headingLevel 有效(1-6)。 */
    HEADING,

    /** 普通正文段落,已按自然段归并。 */
    PARAGRAPH,

    /** 列表项(有序/无序),一项一块。 */
    LIST_ITEM,

    /** 引用块。 */
    QUOTE,

    /** 表格的一行,单元格以 " | " 连接(表格行内再切没有语义价值)。 */
    TABLE_ROW,

    /** 代码块。整体不可再切,切了就不再是代码。 */
    CODE
}
