package com.ragkb.eval;

/**
 * 评估用例的题型。
 *
 * 为什么要分题型而不是只标"对/错":不同题型失败的原因完全不同。
 * 单点事实错,通常是切片粒度或向量模型的问题;跨段落错,往往是切片切断了上下文;
 * 表格数值错,多半是表格被拍平成段落;文档外问题没拒答,则是阈值问题。
 * 不分类的话,你只知道"召回率掉了",不知道去改哪一层。
 */
public enum EvalCaseType {

    /** 单点事实:答案集中在某一个片段里。 */
    FACTOID,

    /** 跨段落:答案需要两个及以上片段共同支撑,最容易暴露切片问题。 */
    MULTI_HOP,

    /** 表格数值:答案来自表格行。PDF 把表格拍平成段落时,这类会最先崩。 */
    TABLE_VALUE,

    /** 文档外:文档里根本没有答案,系统应当拒答。负例,不参与召回率计算。 */
    OUT_OF_SCOPE
}
